/** The Polish form for a count: 1 span, 2 spany, 5 spanów, 22 spany. */
const plural = (n: number, one: string, few: string, many: string) => {
  if (n === 1) return one;
  const tens = n % 100;
  return n % 10 >= 2 && n % 10 <= 4 && (tens < 12 || tens > 14) ? few : many;
};

